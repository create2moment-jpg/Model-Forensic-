"""Trust tooling for findings: why a confidence was given, and what the team says about each finding.

* ``explain_confidence`` — a deterministic explanation from the finding itself: how the evidence was obtained
  (epistemic label), how much evidence there is, whether a noise floor (seed replicates) backs a comparison,
  and what would change the confidence (the analysis' limitations and the hypotheses' falsifying experiments).
* ``record`` / ``report`` — "this is wrong / correct" labels stored locally per finding; the report gives the
  false-alarm rate per analysis, next to the synthetic benchmark in docs/calibration.md.
"""

from __future__ import annotations

from collections import defaultdict
from datetime import datetime, timezone
from typing import Any

from model_forensic.domain.findings import Confidence, EpistemicLabel, Finding
from model_forensic.shared import identity

VERDICTS = ("wrong", "correct", "unsure")

_LABEL_WHY = {
    EpistemicLabel.OBSERVED: "read directly from logged values or the run's configuration",
    EpistemicLabel.COMPUTED: "computed deterministically from logged series / evaluation files",
    EpistemicLabel.INFERRED: "inferred from a pattern in the data — plausible, not proven",
    EpistemicLabel.HYPOTHESIZED: "a hypothesis to be tested",
    EpistemicLabel.RECOMMENDED: "a recommendation derived from other findings",
    EpistemicLabel.AI_GENERATED: "generated by the AI and grounded against the evidence",
}


def explain_confidence(f: Finding) -> dict[str, Any]:
    why = [f"{f.confidence.value.capitalize()} confidence: {_LABEL_WHY.get(f.label, f.label.value)}."]
    n = len(f.evidence)
    why.append(f"{n} piece(s) of evidence" + (", each citing its run and metric." if n else "."))
    runs = f.provenance.runs
    if len(runs) > 2:
        why.append(f"Compared against {len(runs) - 1} baseline run(s) — seed noise is accounted for.")
    elif len(runs) == 2:
        why.append("One baseline run, no seed replicates — a difference could still be run-to-run noise.")
    would: list[str] = list(f.limitations)
    for h in f.hypotheses:
        if h.falsifiable_by:
            would.append(f"Test: {h.falsifiable_by}")
    if len(runs) == 2:
        would.append("Add seed replicates of the baseline (same `group` tag) to measure the noise floor.")
    if f.confidence != Confidence.HIGH and f.label in (EpistemicLabel.INFERRED, EpistemicLabel.HYPOTHESIZED):
        would.append("A controlled run that changes only the suspected cause.")
    return {"why": why, "would_change": list(dict.fromkeys(would))[:6]}


def record(docs: Any, f: Finding, verdict: str, note: str = "") -> dict[str, Any]:
    if verdict not in VERDICTS:
        raise ValueError(f"verdict must be one of {', '.join(VERDICTS)}")
    body = {
        "finding": f.id,
        "analysis": f.provenance.analysis,
        "title": f.title,
        "severity": f.severity.value,
        "verdict": verdict,
        "note": note[:2000],
        "by": identity.current().id,
        "at": datetime.now(timezone.utc).isoformat(),
    }
    docs.put("feedback", f"{f.id}:{body['by']}", body, runs=list(f.provenance.runs))
    docs.audit(body["by"], "finding_feedback", {"finding": f.id, "verdict": verdict})
    return body


def report(docs: Any) -> dict[str, Any]:
    rows: dict[str, dict[str, Any]] = defaultdict(lambda: {"wrong": 0, "correct": 0, "unsure": 0, "examples": []})
    items = docs.list_raw("feedback")
    for it in items:
        r = rows[it.get("analysis", "?")]
        r[it.get("verdict", "unsure")] = r.get(it.get("verdict", "unsure"), 0) + 1
        if it.get("verdict") == "wrong" and len(r["examples"]) < 5:
            r["examples"].append({"title": it.get("title"), "note": it.get("note", "")})
    out = []
    for analysis, r in sorted(rows.items()):
        judged = r["wrong"] + r["correct"]
        out.append(
            {
                "analysis": analysis,
                **r,
                "false_alarm_rate": (r["wrong"] / judged) if judged else None,
            }
        )
    return {"total": len(items), "analyses": out}
